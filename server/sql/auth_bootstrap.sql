-- HC-205: seed test identities

BEGIN;

CREATE TABLE IF NOT EXISTS users (
	id BIGINT PRIMARY KEY,
	nickname VARCHAR(32) NOT NULL UNIQUE,
	CHECK (char_length(nickname) BETWEEN 3 AND 32)
);

DELETE FROM users
WHERE (id = 1 AND nickname <> 'hayseed')
	OR (nickname = 'hayseed' AND id <> 1)
	OR (id = 2 AND nickname <> 'haypeer')
	OR (nickname = 'haypeer' AND id <> 2);

INSERT INTO users (id, nickname)
VALUES
	(1, 'hayseed'),
	(2, 'haypeer')
ON CONFLICT (id) DO UPDATE
SET nickname = EXCLUDED.nickname;

CREATE TABLE IF NOT EXISTS server_roles (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(32) NOT NULL UNIQUE,
	CHECK (char_length(name) BETWEEN 3 AND 32)
);

CREATE TABLE IF NOT EXISTS user_server_roles (
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	role_id BIGINT NOT NULL REFERENCES server_roles(id) ON DELETE CASCADE,
	PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS rooms (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(64) NOT NULL UNIQUE,
	description VARCHAR(256) NOT NULL DEFAULT '',
	created_by_user_id BIGINT NOT NULL REFERENCES users(id),
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CHECK (char_length(name) BETWEEN 1 AND 64)
);

CREATE TABLE IF NOT EXISTS room_members (
	room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (room_id, user_id)
);

CREATE TABLE IF NOT EXISTS chat_messages (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
	sender_user_id BIGINT NOT NULL REFERENCES users(id),
	content TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CHECK (char_length(content) BETWEEN 1 AND 4000)
);

CREATE INDEX IF NOT EXISTS room_members_by_user_id
	ON room_members (user_id, room_id);

CREATE INDEX IF NOT EXISTS chat_messages_by_room_id_and_id
	ON chat_messages (room_id, id DESC);

INSERT INTO server_roles (name)
VALUES ('admin')
ON CONFLICT (name) DO NOTHING;

INSERT INTO user_server_roles (user_id, role_id)
SELECT 1, id
FROM server_roles
WHERE name = 'admin'
ON CONFLICT DO NOTHING;

INSERT INTO rooms (id, name, description, created_by_user_id)
VALUES (1, 'general', 'General discussion', 1)
ON CONFLICT (id) DO UPDATE
SET name = EXCLUDED.name,
	description = EXCLUDED.description;

INSERT INTO room_members (room_id, user_id)
VALUES
	(1, 1),
	(1, 2)
ON CONFLICT DO NOTHING;

COMMIT;

SELECT id, nickname
FROM users
WHERE id IN (1, 2)
ORDER BY id;